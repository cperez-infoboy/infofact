"""Persistence + apply for grouping plans over the live requirement store.

A grouping plan is generated by ``build_grouping_plan`` (dedup, read-only) and
persisted here as ``GroupingPlan`` + ``GroupingGroup`` rows, so the agent
(``/agrupar``) and the requirements UI curate the SAME data. ``apply_plan``
merges the groups whose ``decision`` is ``accept`` via ``merge_requirements``.

Replaces the previous Markdown-file store: the plan is now a DB row, and the
Markdown is a read-only export (``export_plan_md`` → ``serialize_plan_md``).

Idempotency: ``apply_plan`` re-validates every group against the live store on
each call, so a group whose members are already ``MERGED`` into the keeper is
reported ``already_applied`` and skipped — never re-merged (``merge_requirements``
appends revisions, so a blind re-apply would duplicate the audit trail). The
``decision`` per group + ``status`` per plan are the shared guard so the agent
and the UI never double-apply.
"""
from __future__ import annotations

import logging
from datetime import datetime

from sqlalchemy import delete, func, select
from sqlalchemy.ext.asyncio import AsyncSession

from backend.agents.pipelines.grouping import (
    Group,
    GroupingPlan as GroupingPlanData,
    serialize_plan_md,
)
from backend.models.requirement import (
    GroupDecision,
    GroupingGroup,
    GroupingPlan,
    PlanStatus,
    RequirementItem,
    ReqStatus,
)
from backend.services import requirement_store as store

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Persist (GroupingPlan dataclass → DB rows)
# ---------------------------------------------------------------------------

async def persist_plan(
    session: AsyncSession, plan: GroupingPlanData, project_id: int
) -> int:
    """Persist a GroupingPlan (from ``build_grouping_plan``) as DB rows.

    REQ-codes in the plan are resolved to ``RequirementItem`` ids at persist
    time. Groups whose keeper or any member can't be resolved are dropped
    (logged), so a stale ref never blocks persisting the rest.

    Returns the new plan id.
    """
    items = await store.list_requirements(
        session, project_id, include_deleted=True
    )
    by_code = {it.code: it for it in items}

    row = GroupingPlan(project_id=project_id, status=PlanStatus.PROPOSED)
    session.add(row)
    await session.flush()  # populate row.id

    dropped = 0
    for g in plan.groups:
        keeper = by_code.get(g.keeper_code)
        if keeper is None:
            dropped += 1
            continue
        member_ids: list[int] = []
        ok = True
        for code in g.member_codes:
            m = by_code.get(code)
            if m is None:
                ok = False
                break
            member_ids.append(m.id)
        if not ok or not member_ids:
            dropped += 1
            continue
        session.add(GroupingGroup(
            plan_id=row.id,
            keeper_id=keeper.id,
            member_ids=member_ids,
            reason=g.reason,
            confidence=float(g.confidence or 0.0),
            decision=GroupDecision.PENDING,
        ))
    await session.commit()
    if dropped:
        logger.info(
            "persist_plan: dropped %d group(s) with unresolvable refs", dropped
        )
    return row.id


