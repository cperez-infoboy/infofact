# Public function
# ---------------------------------------------------------------------------


async def generate_mer(
    items,
    *,
    project_name: str = "",
    project_description: str = "",
    concurrency: int = DEFAULT_CONCURRENCY,
    enable_critique: bool = True,
    goals: list[Any] | None = None,
    feedback: str = "",
) -> MerResult:
    """Generate a domain entity model (MER) from functional requirements.

    Multi-pass pipeline:

      Pass 1 — entity discovery (narrow schema).
      Pass 2 — gap pass for uncovered REQ codes.
      Pass 3 — attributes + relationships (entity-constrained).
      Pass 4 — deterministic validation.
      Pass 5 — LLM critique (optional, enabled by default).

    Takes RequirementItem objects (filtered to functional/data/process types)
    and produces a MerResult with entities, relationships, a Mermaid erDiagram
    string rendered deterministically from the structured LLM output, plus
    validation warnings and critique findings in stats.

    Each pass has its own retry loop (transient backoff + parse retries,
    mirroring classification._classify_item). Failed passes degrade
    gracefully — a failed gap pass returns no extra candidates, a failed
    critique returns no findings — instead of aborting the whole pipeline.
    """
    if not items:
        return MerResult(stats={"input": 0})

    # Pass 1: entity discovery.
    candidates = await _discover_entities(
        items, project_name, project_description,
        goals=goals, feedback=feedback,
    )

    # Pass 2: gap pass for uncovered requirements.
    gap_candidates = await _gap_pass(
        items, candidates, project_name, project_description,
        goals=goals, feedback=feedback,
    )
    all_candidates = candidates + gap_candidates

    # Pass 3: attributes + relationships (entity-constrained).
    entities_full, relationships = await _detail_entities_relationships(
        items, all_candidates, project_name, project_description,
        goals=goals, feedback=feedback,
    )

    # Normalize cardinalities to canonical forms before validation/rendering.
    for rel in relationships:
        rel.cardinality = _normalize_cardinality(rel.cardinality)

    # Pass 4: deterministic validation.
    warnings = _validate_mer(entities_full, relationships)

    # Pass 5: LLM critique (optional).
    critique_findings: list[MerCritiqueFinding] = []
    if enable_critique:
        critique_findings = await _critique_mer(
            entities_full, relationships, items, project_name,
            project_description, goals=goals,
        )

    # Pass 6: narrative description (lightweight, always runs).
    description = await _describe_mer(
        entities_full, relationships, items, project_name,
        project_description, goals=goals,
    )

    # Render Mermaid erDiagram deterministically.
    mermaid = _render_mermaid(entities_full, relationships)

    # Compute coverage stats.
    input_codes = {it.code for it in items}
    covered_codes = {c for e in entities_full for c in e.traced_req_codes}
    uncovered = input_codes - covered_codes

    stats = {
        "input": len(items),
        "entities": len(entities_full),
        "relationships": len(relationships),
        "aggregate_roots": sum(1 for e in entities_full if e.aggregate_root),
        "bounded_contexts": len(
            {e.bounded_context for e in entities_full if e.bounded_context}
        ),
        "req_coverage": f"{len(covered_codes)}/{len(input_codes)}",
        "uncovered_codes": sorted(uncovered),
        "gap_pass_found": len(gap_candidates),
        "validation_warnings": warnings,
        "critique_findings": [f.model_dump() for f in critique_findings],
        "critique_blockers": sum(
            1 for f in critique_findings if f.severity == "blocker"
        ),
    }
    logger.info(
        "generate_mer: %d items -> %d entities, %d relationships "
        "(gap +%d, %d warnings, %d critique findings)",
        stats["input"],
        stats["entities"],
        stats["relationships"],
        stats["gap_pass_found"],
        len(warnings),
        len(critique_findings),
    )
    return MerResult(
        entities=entities_full,
        relationships=relationships,
        mermaid=mermaid,
        description=description,
        stats=stats,
    )
