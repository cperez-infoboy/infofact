"""MER pipeline: domain entity model extraction from functional requirements.

Multi-pass pipeline (5 passes):

  Pass 1 — entity discovery (narrow schema: no attributes, no relationships).
  Pass 2 — gap pass: re-scan requirements whose REQ codes were not traced.
  Pass 3 — attributes + relationships (entity-constrained to the Pass 1+2 list).
  Pass 4 — deterministic validation (PK, dangling refs, duplicates, cardinality).
  Pass 5 — LLM critique covering documented failure modes (optional).

Takes the functional RequirementItems (types: functional, data, process) and
produces a domain entity model (MER — Modelo Entidad-Relacion). The Mermaid
erDiagram is rendered deterministically in code from the structured output,
not generated by the LLM, so the diagram is always syntactically valid and
matches the entities/relationships exactly.

Design notes (mirrors classification.py patterns):

- Does NOT write to the DB. Returns a MerResult dataclass consumed by the
  analysis assembler / store layer.
- Uses structured_llm with narrow per-pass schemas for fence-tolerant
  structured output (Z.ai GLM wraps JSON in fences).
- Retry policy: transient (429/5xx/timeout) with exponential backoff, plus
  parse-failure retries (mirrors _classify_item).
- Prompts are in Spanish neutro (no voseo, no spanglish) following project
  conventions for LLM-facing text.
"""
