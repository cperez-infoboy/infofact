# ---------------------------------------------------------------------------
# Mermaid erDiagram rendering (deterministic, from structured output)
# ---------------------------------------------------------------------------

# Mermaid erDiagram cardinality notation:
#   1:1  -> ||--||   (exactly one to exactly one)
#   1:N  -> ||--o{   (one to zero-or-many)
#   N:M  -> }o--o{   (zero-or-many to zero-or-many)
_MERMAID_CARDINALITY = {
    "1:1": "||--||",
    "1:N": "||--o{",
    "N:M": "}o--o{",
}


def _mermaid_attr_line(attr: dict) -> str:
    """Render one attribute as a Mermaid erDiagram column line."""
    type_str = attr.get("type", "string")
    name = attr.get("name", "field")
    if attr.get("is_key"):
        return f"    {type_str} {name} PK"
    return f"    {type_str} {name}"


def _render_mermaid(
    entities: list[MerEntitySchema],
    relationships: list[MerRelationshipSchema],
) -> str:
    """Render a Mermaid erDiagram from structured entity/relationship output.

    Produces valid Mermaid syntax:
        erDiagram
            ENTITY_A {
                string id PK
                string name
            }
            ENTITY_A ||--o{ ENTITY_B : "has"

    Entity names are sanitized to alphanumeric + underscore (Mermaid
    identifiers). Relationship labels are quoted to allow spaces.

    Each entity is assigned a ``classDef`` color based on its bounded
    context. Aggregate roots receive a gold border (stroke-width 3px).
    Entities without a bounded context get the default gray styling.
    """
    if not entities:
        return "erDiagram"

    lines: list[str] = ["erDiagram"]

    # Entity blocks
    for ent in entities:
        # Mermaid identifiers: uppercase alphanumeric + underscore.
        ent_id = ent.name.replace(" ", "_").upper()
        lines.append(f"    {ent_id} {{")
        for attr in ent.attributes:
            lines.append(_mermaid_attr_line(attr.model_dump()))
        lines.append("    }")

    # Relationship edges
    for rel in relationships:
        from_id = rel.from_entity.replace(" ", "_").upper()
        to_id = rel.to_entity.replace(" ", "_").upper()
        card = _MERMAID_CARDINALITY.get(rel.cardinality.strip(), "||--o{")
        label = rel.label or "relates_to"
        lines.append(f'    {from_id} {card} {to_id} : "{label}"')

    # classDef + class assignments for semantic coloring by bounded context.
    unique_bcs = sorted(
        {e.bounded_context for e in entities if e.bounded_context}
    )
    bc_to_idx: dict[str, int] = {bc: i for i, bc in enumerate(unique_bcs)}
    for i, _bc in enumerate(unique_bcs):
        fill, stroke = BC_PALETTE[i % len(BC_PALETTE)]
        lines.append("    " + class_def(f"bc{i}", fill, stroke))
    # Entities without BC get gray.
    lines.append(
        "    "
        + class_def("bc_default", NETWORK_DEFAULT[0], NETWORK_DEFAULT[1])
    )
    # Aggregate root highlight: gold border, thicker.
    lines.append(
        "    "
        + class_def(
            "agg_root",
            NETWORK_DEFAULT[0],
            AGGREGATE_ROOT_STROKE,
            sw=3,
        )
    )
    for ent in entities:
        ent_id = ent.name.replace(" ", "_").upper()
        if ent.bounded_context and ent.bounded_context in bc_to_idx:
            cls = f"bc{bc_to_idx[ent.bounded_context]}"
        else:
            cls = "bc_default"
        lines.append(f"    class {ent_id} {cls}")
        if ent.aggregate_root:
            lines.append(f"    class {ent_id} agg_root")

    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Cardinality normalization
# ---------------------------------------------------------------------------


def _normalize_cardinality(value: str) -> str:
    """Normalize cardinality strings to the canonical 1:1 / 1:N / N:M forms."""
    v = value.strip().upper().replace(" ", "")
    # Common variants the LLM might emit.
    variants = {
        "1:1": "1:1", "1-1": "1:1", "UNO:AUNO": "1:1", "ONE-TO-ONE": "1:1",
        "1:N": "1:N", "1-N": "1:N", "1:M": "1:N", "ONE-TO-MANY": "1:N",
        "UNO:AN": "1:N", "N:M": "N:M", "N-M": "N:M", "M:N": "N:M", "M-N": "N:M",
        "MANY-TO-MANY": "N:M", "N:AN": "N:M",
    }
    return variants.get(v, "1:N")  # default to 1:N (most common)


