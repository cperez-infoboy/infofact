def _build_items_text(
    items,
    project_name: str = "",
    project_description: str = "",
    goals: list[Any] | None = None,
    feedback: str = "",
) -> str:
    """Build the user message text from functional requirement items."""
    lines: list[str] = []
    if feedback:
        lines.append(_format_feedback(feedback).rstrip())
        lines.append("")
    if goals:
        lines.append(
            _format_goals(goals, section_title="OBJETIVOS DEL SISTEMA").rstrip()
        )
        lines.append("")
    if project_name:
        lines.append(f"PROYECTO: {project_name}")
    if project_description:
        lines.append(f"DESCRIPCION: {project_description}")
    lines.append("")

    for it in items:
        lines.append(f"REQ_CODE: {it.code}")
        lines.append(f"TYPE: {it.type.value}")
        lines.append(f"STATEMENT: {it.statement}")
        if it.source:
            src = it.source
            if isinstance(src, dict):
                quote = src.get("quote") or src.get("section") or ""
            elif isinstance(src, list) and src:
                quote = src[0].get("quote", "") if isinstance(src[0], dict) else str(src[0])
            else:
                quote = str(src)
            if quote:
                lines.append(f"SOURCE: {quote[:300]}")
        lines.append("")

    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Pass 1: entity discovery (narrow schema)
# ---------------------------------------------------------------------------


async def _discover_entities(
    items,
    project_name: str,
    project_description: str,
    goals: list[Any] | None = None,
    feedback: str = "",
) -> list[EntityCandidate]:
    """Pass 1: entity discovery with narrow schema (no attributes, no relationships)."""
    user_text = _build_items_text(
        items, project_name, project_description,
        goals=goals, feedback=feedback,
    )
    msgs = [("system", _ENTITY_DISCOVERY_PROMPT), ("human", user_text)]
    llm = structured_llm(EntityDiscoverySchema)
    try:
        result = await _invoke_with_retry(
            llm, msgs, context_label="mer_discover"
        )
        return list(result.entities)
    except Exception:
        logger.exception("_discover_entities: all retries exhausted")
        return []


# ---------------------------------------------------------------------------
# Pass 2: gap pass for uncovered requirements
# ---------------------------------------------------------------------------


async def _gap_pass(
    items,
    candidates: list[EntityCandidate],
    project_name: str,
    project_description: str,
    goals: list[Any] | None = None,
    feedback: str = "",
) -> list[EntityCandidate]:
    """Pass 2: detect uncovered REQ codes and re-scan them."""
    input_codes = {it.code for it in items}
    covered_codes = {c for e in candidates for c in e.traced_req_codes}
    uncovered = input_codes - covered_codes
    if not uncovered:
        return []

    uncovered_items = [it for it in items if it.code in uncovered]
    user_text = _build_items_text(
        uncovered_items, project_name, project_description,
        goals=goals, feedback=feedback,
    )
    already_listed = ", ".join(e.name for e in candidates) or "(ninguna)"
    user_text += (
        f"\nENTIDADES YA IDENTIFICADAS: {already_listed}\n"
        "Revisa SOLO los requerimientos anteriores y determina si generan "
        "entidades NUEVAS (no listadas arriba).\n"
    )
    msgs = [("system", _GAP_PASS_PROMPT), ("human", user_text)]
    llm = structured_llm(EntityDiscoverySchema)
    try:
        result = await _invoke_with_retry(
            llm, msgs, context_label="mer_gap_pass"
        )
        return list(result.entities)
    except Exception:
        logger.exception("_gap_pass: all retries exhausted")
        return []


# ---------------------------------------------------------------------------
# Pass 3: attributes + relationships (entity-constrained)
# ---------------------------------------------------------------------------


async def _detail_entities_relationships(
    items,
    candidates: list[EntityCandidate],
    project_name: str,
    project_description: str,
    goals: list[Any] | None = None,
    feedback: str = "",
) -> tuple[list[MerEntitySchema], list[MerRelationshipSchema]]:
    """Pass 3: given the finalized entity list, extract attributes + relationships.

    Merges candidate metadata (description, aggregate_root, bounded_context,
    traced_req_codes) with the detail entities (attributes) matched by name
    (case-insensitive). Builds full MerEntitySchema objects from the merged data.
    """
    entity_list_str = "\n".join(f"- {c.name}" for c in candidates)
    user_text = _build_items_text(
        items, project_name, project_description,
        goals=goals, feedback=feedback,
    )
    user_text += (
        f"\nENTIDADES DEL DOMINIO (usa SOLO estos nombres):\n"
        f"{entity_list_str}\n"
    )
    msgs = [("system", _DETAIL_PROMPT), ("human", user_text)]
    llm = structured_llm(MerDetailSchema)
    try:
        detail = await _invoke_with_retry(
            llm, msgs, context_label="mer_detail"
        )
    except Exception:
        logger.exception(
            "_detail_entities_relationships: all retries exhausted"
        )
        # Fallback: return candidates as entities without attributes.
        fallback_entities = [
            MerEntitySchema(
                name=c.name,
                description=c.description,
                aggregate_root=c.aggregate_root,
                bounded_context=c.bounded_context,
                traced_req_codes=c.traced_req_codes,
            )
            for c in candidates
        ]
        return (fallback_entities, [])

    # Merge candidates + detail by lowercase name.
    candidate_lookup = {c.name.lower(): c for c in candidates}
    entities_full: list[MerEntitySchema] = []
    for det_ent in detail.entities:
        c = candidate_lookup.get(det_ent.name.lower())
        if c:
            entities_full.append(
                MerEntitySchema(
                    name=c.name,
                    description=c.description,
                    attributes=det_ent.attributes,
                    aggregate_root=c.aggregate_root,
                    bounded_context=c.bounded_context,
                    traced_req_codes=c.traced_req_codes,
                )
            )
        else:
            # Entity from detail not in candidates — include with empty metadata.
            entities_full.append(
                MerEntitySchema(name=det_ent.name, attributes=det_ent.attributes)
            )

    relationships = list(detail.relationships)
    return (entities_full, relationships)


# ---------------------------------------------------------------------------
# Pass 4: deterministic validation
# ---------------------------------------------------------------------------


def _validate_mer(
    entities: list[MerEntitySchema],
    relationships: list[MerRelationshipSchema],
) -> list[str]:
    """Pass 4: deterministic validation checks (no LLM).

    Returns a list of warning strings. Each warning describes one issue found.
    An empty list means the model passed all deterministic checks.
    """
    warnings: list[str] = []
    entity_names_lower = {e.name.lower() for e in entities}

    # Check: no duplicate entity names (case-insensitive).
    seen: set[str] = set()
    for e in entities:
        lower = e.name.lower()
        if lower in seen:
            warnings.append(
                f"Entidad duplicada (ignorando mayusculas): {e.name}"
            )
        seen.add(lower)

    # Check: every entity has at least one PK.
    for e in entities:
        if not any(a.is_key for a in e.attributes):
            warnings.append(
                f"Entidad sin PK (is_key=True): {e.name}"
            )

    # Check: relationships reference existing entities.
    for rel in relationships:
        if rel.from_entity.lower() not in entity_names_lower:
            warnings.append(
                f"Relacion referencia entidad inexistente (from_entity): "
                f"{rel.from_entity}"
            )
        if rel.to_entity.lower() not in entity_names_lower:
            warnings.append(
                f"Relacion referencia entidad inexistente (to_entity): "
                f"{rel.to_entity}"
            )

    # Check: valid cardinality values.
    valid_cardinalities = {"1:1", "1:N", "N:M"}
    for rel in relationships:
        if rel.cardinality not in valid_cardinalities:
            warnings.append(
                f"Cardinalidad invalida '{rel.cardinality}' en relacion "
                f"{rel.from_entity} -> {rel.to_entity}"
            )

    return warnings


# ---------------------------------------------------------------------------
# Pass 5: LLM critique
# ---------------------------------------------------------------------------


async def _critique_mer(
    entities: list[MerEntitySchema],
    relationships: list[MerRelationshipSchema],
    items,
    project_name: str,
    project_description: str,
    goals: list[Any] | None = None,
) -> list[MerCritiqueFinding]:
    """Pass 5: LLM critique covering documented failure modes."""
    # Build summaries.
    entity_lines = []
    for e in entities:
        attrs = ", ".join(a.name for a in e.attributes[:5]) or "(sin atributos)"
        entity_lines.append(f"- {e.name} ({attrs})")
    entity_summary = "\n".join(entity_lines) or "(ninguna)"

    rel_lines = []
    for r in relationships:
        rel_lines.append(
            f"- {r.from_entity} {r.cardinality} {r.to_entity}: {r.label}"
        )
    rel_summary = "\n".join(rel_lines) or "(ninguna)"

    req_lines = [f"- {it.code}: {it.statement[:100]}" for it in items[:30]]
    req_summary = "\n".join(req_lines)
    if len(items) > 30:
        req_summary += f"\n... ({len(items) - 30} mas)"

    header_lines = []
    if project_name:
        header_lines.append(f"PROYECTO: {project_name}")
    if project_description:
        header_lines.append(f"DESCRIPCION: {project_description}")
    header = "\n".join(header_lines)

    goals_block = (
        _format_goals(goals, section_title="OBJETIVOS DEL SISTEMA")
        if goals
        else ""
    )

    user_text = (
        f"{header}\n\n"
        f"{goals_block}"
        f"REQUERIMIENTOS ORIGINALES:\n{req_summary}\n\n"
        f"ENTIDADES DEL MER GENERADO:\n{entity_summary}\n\n"
        f"RELACIONES DEL MER GENERADO:\n{rel_summary}\n"
    )
    msgs = [("system", _CRITIQUE_PROMPT), ("human", user_text)]
    llm = structured_llm(MerCritiqueSchema)
    try:
        result = await _invoke_with_retry(
            llm, msgs, context_label="mer_critique"
        )
        return list(result.findings)
    except Exception:
        logger.exception("_critique_mer: all retries exhausted")
        return []


